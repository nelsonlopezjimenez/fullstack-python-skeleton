// MAINTAINER ONLY: rebuild app/static/vendor/react-all.js after changing a version in package.json.
//
//   cd tools/vendor-react
//   npm ci          (needs internet, or a Verdaccio registry)
//
// [ADVANCED] Keep package-lock.json pointing at https://registry.npmjs.org/. If your npm uses a
// local Verdaccio, npm writes http://localhost:4873/ into the lock: replace it before committing
// (the sha512 integrity hashes are the same, so npm ci still verifies every package).
//   npm run build
//
// Then commit app/static/vendor/react-all.js. Students and lab machines never run this:
// they get the finished file with the repo, like app/static/htmx.min.js.
import { build } from 'esbuild'

await build({
  entryPoints: ['entry.js'],
  outfile: '../../app/static/vendor/react-all.js',
  bundle: true,
  format: 'esm',
  target: 'es2022',
  // [BEGINNER] The DEVELOPMENT build of React, like `npm run dev`: readable stack traces and
  // the helpful warnings (missing `key`, StrictMode double effects). Bigger, but this is a classroom.
  define: { 'process.env.NODE_ENV': '"development"' },
  // Keep the libraries' license headers (MIT, Apache-2.0) at the end of the file.
  legalComments: 'eof',
  banner: {
    js: '// Vendored: react, react-dom/client, react-router, htm (versions: tools/vendor-react/package.json).\n' +
        '// Generated by tools/vendor-react/build.mjs. Do not edit by hand.'
  },
  // React Router's development build too (it has its own warnings), to match React's.
  conditions: ['development'],
  logLevel: 'info'
})
